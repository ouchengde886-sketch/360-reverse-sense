import sys,struct
sys.stdout.reconfigure(encoding='utf-8')
b1=0x8BEC8B55; b2=0x6AEC8B55
print("  0x2A6830 指向的内容首 DWORD = 0x%08X" % b1)
print("    字节序列: %s" % ' '.join('%02X'%c for c in struct.pack('<I',b1)))
print("    这是机器码: 55 8B EC 8B = push ebp; mov ebp,esp; mov ...")
print()
print("  0x2A682C 指向的内容首 DWORD = 0x%08X" % b2)
print("    字节序列: %s" % ' '.join('%02X'%c for c in struct.pack('<I',b2)))
print("    这是机器码: 55 8B EC 6A = push ebp; mov ebp,esp; push ...")
print()
print("  => 这两个全局存的**不是对象指针，是函数指针**！")
print("     0x40073 的 +0x2BA: call edi  就是调用这个函数来创建对象。")
print()
print("  重新看 0x40073 的 +0xE0 区域:")
print("    +0E0: 85 C0                 test eax,eax")
print("    +0E2: 74 0D                 jz +0xF1")
print("    +0E4: 89 3D 2C 68 2A 10    mov [0x102A682C],edi")
print("    +0EA: A3 30 68 2A 10       mov [0x102A6830],eax")
print()
print("  edi 从哪来？看 +0x2A7 附近:")
print("    +2A7: 8B 3D 2C 68 2A 10    mov edi,[0x102A682C]")
print("    +2AD: 85 FF                 test edi,edi")
print("    +2AF: 0F 84 1B 01 00 00    jz 失败")
print("    +2B5: 83 3D 30 68 2A 10 00 cmp dword[0x102A6830],0")
print("    +2BC: 0F 84 0E 01 00 00    jz 失败")
print("    +2C2: FF D7                 call edi        ★ 调用工厂函数")
print("    +2C4: 8B F0                 mov esi,eax     ★ esi = 新对象")
print()
print("  => esi 是 call edi 的返回值，是**真正的引擎对象**。")
print("     而 0x2A682C/0x2A6830 存的是**工厂函数指针**。")
print()
print("  所以我要 dump 的是 esi，不是 [0x2A6830]。")
print("  但 esi 是局部变量，调用结束后就没了。")
print()
print("  不过 vtable+0x18 是在函数内部通过 esi 调的：")
print("    +2FC: 8B 06       mov eax,[esi]    ; esi 的虚表")
print("    +306: FF 50 18    call [eax+0x18]  ; 虚表+0x18")
print()
print("  所以关键还是 esi 的虚表。esi = call edi 的返回值。")
print("  我可以自己调一次 call edi，拿到 esi，然后 dump 它的虚表！")
